# Задача 7.2. Обчислення N-го числа Фібоначчі за допомогою циклу while

n = int(input("Введіть номер числа Фібоначчі (N >= 0): "))

if n == 0:
    print("0-е число Фібоначчі: 0")
elif n == 1:
    print("1-е число Фібоначчі: 1")
else:
    a = 0
    b = 1
    count = 2

    while count <= n:
        next_num = a + b
        a = b
        b = next_num
        count += 1

    print(f"{n}-е число Фібоначчі: {b}")